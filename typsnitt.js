// Text i pixeltypsnittet som HTML: ett SVG per ord (så att raderna bryts
// mellan orden som vanlig text) och den riktiga texten osynligt bredvid,
// för skärmläsare och för testerna. `px` = skärmpixlar per pixel i
// typsnittet.
function pixeltext(text, px) {
    const T = TYPSNITT;
    const ord = String(text).split(' ').filter(o => o).map(o => {
        let x = 0, d = '';
        for (const c of o) {
            const rader = (T.tecken[c] || T.tecken['?']).split(' ');
            const bredd = rader[0].length;
            rader.forEach((rad, y) => {
                // Slå ihop pixlar i rad till en rektangel
                let i = 0;
                while (i < rad.length) {
                    if (rad[i] !== '#') { i++; continue; }
                    let j = i;
                    while (j < rad.length && rad[j] === '#') j++;
                    d += 'M' + (x + i) + ' ' + y + 'h' + (j - i) + 'v1h' + (i - j) + 'z';
                    i = j;
                }
            });
            x += bredd + T.mellanrum;
        }
        const b = x - T.mellanrum;
        return '<svg viewBox="0 0 ' + b + ' ' + T.hojd + '" width="' + b * px +
            '" height="' + T.hojd * px + '" style="margin:' + px + 'px ' + T.ordMellanrum * px / 2 +
            'px" shape-rendering="crispEdges" aria-hidden="true">' +
            '<path fill="currentColor" d="' + d + '"/></svg>';
    });
    return '<span class="pixeltext">' + ord.join(' ') +
        '<span class="osynlig">' + text + '</span></span>';
}
